/**
 * Get app icon - prioritizes Firestore icon, falls back to mapping
 * @param {string} packageName - Android package name
 * @param {string} firestoreIcon - Base64 icon from Firestore (if available)
 * @returns {object} Icon info with either img src or svg
 */
export function getAppIcon(packageName, firestoreIcon = null) {
  // Priority 1: Use icon from Firestore if available
  if (firestoreIcon) {
    return {
      type: "image",
      src: firestoreIcon,
      name: APP_ICONS[packageName]?.name || packageName,
    };
  }

  // Priority 2: Use mapped icon
  const mapped = APP_ICONS[packageName];
  if (mapped) {
    return {
      type: "svg",
      svg: mapped.svg,
      color: mapped.color,
      name: mapped.name,
      textColor: mapped.textColor,
    };
  }

  // Priority 3: Default icon
  return {
    type: "svg",
    svg: APP_ICONS.default.svg,
    color: APP_ICONS.default.color,
    name: packageName,
  };
}

/**
 * Render app icon as HTML
 * @param {string} packageName - Android package name
 * @param {string} firestoreIcon - Base64 icon from Firestore (if available)
 * @param {number} size - Icon size in pixels
 * @returns {string} HTML string for the icon
 */
export function renderAppIcon(packageName, firestoreIcon = null, size = 40) {
  const icon = getAppIcon(packageName, firestoreIcon);

  if (icon.type === "image") {
    return `<img src="${icon.src}" alt="${icon.name}" style="width:${size}px;height:${size}px;border-radius:8px;object-fit:cover;" />`;
  }

  // SVG icon with background
  return `
    <div style="width:${size}px;height:${size}px;border-radius:8px;background:${
      icon.color
    };display:flex;align-items:center;justify-content:center;">
      <div style="width:${size * 0.6}px;height:${size * 0.6}px;color:${
        icon.textColor || "#fff"
      };">
        ${icon.svg.replace(
          /fill="[^"]*"/,
          `fill="${icon.textColor || "#fff"}"`,
        )}
      </div>
    </div>
  `;
}
